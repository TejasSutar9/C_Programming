//Accept one number from user and print that number of * on screen 

///////////////////////////////////////////////////////////////////////
//
//  Required Header File
//
///////////////////////////////////////////////////////////////////////

#include<stdio.h>
#include<stdbool.h>

///////////////////////////////////////////////////////////////////////
//
//  Function Name : Accept
//  Description :   To print the number of * on screen
//  Input :         int
//  Output :        int
//  Author :        Tejas Pradip Sutar
//  Date :          16/10/2025
//
///////////////////////////////////////////////////////////////////////

void Accept(int iNo)
{
    int iCnt = 0;                       //To store result

    for(iCnt = 1; iCnt <= iNo; iCnt++)
    {
        printf("*");
    }
}//End of Accept

///////////////////////////////////////////////////////////////////////
//
//  Entry point function for the application
//
///////////////////////////////////////////////////////////////////////

int main()
{
    int iValue = 0;
    iValue = 5;

    Accept(iValue);                         //Method call

    return 0;
}//End of main

